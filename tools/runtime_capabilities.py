"""Generate (and check) the capability-gap table in ``docs/RUNTIMES.md``.

    python tools/runtime_capabilities.py            # print the report
    python tools/runtime_capabilities.py --write    # update docs/RUNTIMES.md in place
    python tools/runtime_capabilities.py --check    # exit 1 if the docs are stale

Each built-in runtime is built through its own registered factory against a
fully featured probe context (fake model that streams and supports structured
output, in-memory session and memory stores, an MCP manager), so the table shows
what the runtime reports when every service is configured.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
DOC = ROOT / "docs" / "RUNTIMES.md"
START = "<!-- capability-gaps:start (generated by tools/runtime_capabilities.py) -->"
END = "<!-- capability-gaps:end -->"

#: Runtimes shown in the table, in order.
RUNTIMES = ("custom", "google-adk", "langgraph")


class RuntimeNotInstalledError(RuntimeError):
    """A built-in runtime's optional dependency is missing."""


def collect() -> dict[str, object]:
    """Capabilities each built-in runtime reports against the probe context."""
    from micro_agent.config.runtimes import register_builtin_runtimes
    from micro_agent.definition import load_definition_from_dict
    from micro_agent.mcp import McpConnectionManager
    from micro_agent.memory import InMemoryMemoryProvider
    from micro_agent.models import FakeModelProvider, ProviderCapabilities
    from micro_agent.observability import Telemetry
    from micro_agent.runtime import RuntimeBuildContext, get_runtime_registration
    from micro_agent.session import InMemorySessionProvider

    class _FullFeaturedModel(FakeModelProvider):
        def capabilities(self) -> ProviderCapabilities:
            return ProviderCapabilities(tool_use=True, streaming=True, structured_output=True)

    register_builtin_runtimes()
    definition = load_definition_from_dict(
        {
            "apiVersion": "microagents.io/v1alpha1",
            "kind": "MicroAgent",
            "metadata": {"name": "capability-probe", "version": "1.0.0"},
            "spec": {
                "behavior": {"instructions": "probe"},
                "dependencies": {"model": {"ref": "probe", "provider": "fake"}},
            },
        }
    )
    context = RuntimeBuildContext(
        definition=definition,
        model_provider=_FullFeaturedModel(),
        model_api_key=None,
        session_provider=InMemorySessionProvider(),
        memory_provider=InMemoryMemoryProvider(),
        operation_registry=None,
        approval_store=None,
        knowledge_provider=None,
        mcp_manager=McpConnectionManager(),
        policy=None,
        audit=None,
        telemetry=Telemetry(),
        tool_registry={},
    )
    result: dict[str, object] = {}
    for name in RUNTIMES:
        try:
            runtime = get_runtime_registration(name).factory(context)
        except ImportError as exc:
            raise RuntimeNotInstalledError(f"{name}: {exc}") from exc
        result[name] = runtime.capabilities()
    return result


def report() -> str:
    from micro_agent.runtime.gaps import render_capability_gaps

    return render_capability_gaps(collect())  # type: ignore[arg-type]


def embedded(text: str) -> str:
    """The generated block currently embedded in the document."""
    start = text.index(START) + len(START)
    return text[start : text.index(END)].strip("\r\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="update docs/RUNTIMES.md")
    mode.add_argument("--check", action="store_true", help="fail when docs/RUNTIMES.md is stale")
    args = parser.parse_args(argv)

    try:
        generated = report()
    except RuntimeNotInstalledError as exc:
        print(f"cannot build every runtime ({exc}); install the adk and langgraph extras")
        return 2
    if not (args.write or args.check):
        print(generated)
        return 0

    raw = DOC.read_text(encoding="utf-8")
    newline = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    if args.check:
        if embedded(text) == generated:
            print("capability table is current")
            return 0
        print(
            "docs/RUNTIMES.md capability table is stale; "
            "run: python tools/runtime_capabilities.py --write"
        )
        return 1
    start = text.index(START) + len(START)
    updated = text[:start] + "\n" + generated + "\n" + text[text.index(END) :]
    DOC.write_text(updated.replace("\n", newline), encoding="utf-8", newline="")
    print("updated docs/RUNTIMES.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
